package face.idl.model.v4;

/**
 * Represents the various integer data types supported in IDL.
 * This enum defines both signed and unsigned integer types of different sizes.
 */
public enum IntegerDataTypes {
    None,
    SignedShort,
    SignedLong,
    SignedLongLong,
    SignedTiny,
    UnsignedShort,
    UnsignedLong,
    UnsignedLongLong,
    UnsignedTiny
}
